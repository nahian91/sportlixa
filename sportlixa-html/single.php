            Expect Kansas City to test Buffalo's perimeter tackling early with screen passes and jet sweeps before taking deep shots down the boundary to Xavier Worthy. If the Bills cannot contain the underneath chunk plays, Mahomes will control time of possession and keep Allen on the sideline.
